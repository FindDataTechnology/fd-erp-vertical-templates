#!/usr/bin/env python3
"""刷新连接器目录 service id 快照（供 tests 侧的绑定声明门使用）。

绑定声明里的 `provider` 必须是萬星连接器目录真实存在的 service id。目录在
`open-connector-mt` 仓、CI 里读不到，所以这里把 id 集快照进本仓（与 paas
`lib/wire-tool-risk.js` 同一手法：快照 + 本地刷新 + 有 checkouts 时逐值比对）。

用法：
    python3 scripts/refresh_connector_catalog_ids.py            # 重写快照；有变化退出 2
    python3 scripts/refresh_connector_catalog_ids.py --check    # 只比对；漂移退出 1

默认从 ~/finddata/open-connector-mt 读，可用 CONNECTOR_CATALOG_DIR 覆盖。
目录文件是 `npm run generate:catalog` 的生成物，本脚本只读它、不碰 src/providers。
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SNAPSHOT = REPO / "tests" / "fixtures" / "connector-catalog-service-ids.json"
ACTIONS_SNAPSHOT = REPO / "tests" / "fixtures" / "connector-binding-actions.json"

# 只需要快照"被绑定引用的 provider"的动作集——全目录 1570 家的动作太多，而面级门的判据
# 只覆盖我们真正声明过的那些（见 docs/connector-binding-surfaces.md）。
BOUND_PROVIDERS = ("alipay", "kingdee", "meituan", "shopify", "shopify_admin", "wechatpay")


def catalog_dir() -> Path:
    return Path(os.environ.get("CONNECTOR_CATALOG_DIR")
                or Path.home() / "finddata" / "open-connector-mt")


def read_service_ids() -> list[str]:
    apps = catalog_dir() / "catalog" / "apps"
    if not apps.is_dir():
        raise SystemExit(
            f"[catalog-ids] 找不到目录：{apps}（设 CONNECTOR_CATALOG_DIR 指向 open-connector-mt）"
        )
    ids: list[str] = []
    for path in sorted(apps.glob("*.json")):
        try:
            body = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:  # 目录坏了要吵，不要静默少一个 id
            raise SystemExit(f"[catalog-ids] {path}: 不是合法 JSON（{exc}）") from exc
        service = body.get("service") or path.stem
        if not isinstance(service, str) or not service:
            raise SystemExit(f"[catalog-ids] {path}: 缺 service 字段")
        ids.append(service)
    if len(set(ids)) != len(ids):
        dupes = sorted({i for i in ids if ids.count(i) > 1})
        raise SystemExit(f"[catalog-ids] 目录内 service id 重复：{dupes}")
    return sorted(ids)


def read_actions() -> dict[str, list[dict[str, str]]]:
    """被绑定引用的 provider 的动作集：(name, operationType)。缺 provider 要吵，不要静默少一条。"""
    apps = catalog_dir() / "catalog" / "apps"
    out: dict[str, list[dict[str, str]]] = {}
    missing: list[str] = []
    for service in BOUND_PROVIDERS:
        path = apps / f"{service}.json"
        if not path.is_file():
            missing.append(service)
            continue
        body = json.loads(path.read_text(encoding="utf-8"))
        out[service] = [
            {"name": str(a.get("name")), "operationType": str(a.get("operationType"))}
            for a in body.get("actions") or []
            if a.get("name")
        ]
    if missing:
        raise SystemExit(f"[catalog-ids] 目录里找不到被引用的 provider：{missing}")
    return dict(sorted(out.items()))


def render_actions(actions: dict[str, list[dict[str, str]]]) -> str:
    body = {
        "_comment": (
            "generated by scripts/refresh_connector_catalog_ids.py — do not hand-edit. "
            "被绑定引用的 provider 的动作集快照，供 tests 的面级对位门在无目录 checkout 时"
            "（CI）也能核对：表里点名的动作必须真的存在。"
        ),
        "source": "open-connector-mt/catalog/apps",
        "providers": actions,
    }
    return json.dumps(body, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def render(ids: list[str]) -> str:
    body = {
        "_comment": (
            "generated by scripts/refresh_connector_catalog_ids.py — do not hand-edit. "
            "连接器目录（open-connector-mt/catalog/apps/*.json）的 service id 集，"
            "供 tests/test_connector_binding_providers.py 校验绑定声明。"
        ),
        "source": "open-connector-mt/catalog/apps",
        "count": len(ids),
        "service_ids": ids,
    }
    return json.dumps(body, ensure_ascii=False, indent=2) + "\n"


def main() -> int:
    check = "--check" in sys.argv
    actions_rendered = render_actions(read_actions())
    actions_before = ACTIONS_SNAPSHOT.read_text(encoding="utf-8") if ACTIONS_SNAPSHOT.exists() else None
    actions_changed = actions_before != actions_rendered
    if actions_changed and not check:
        ACTIONS_SNAPSHOT.parent.mkdir(parents=True, exist_ok=True)
        ACTIONS_SNAPSHOT.write_text(actions_rendered, encoding="utf-8")
        print(f"[catalog-ids] 已写入 {ACTIONS_SNAPSHOT}")
    elif actions_changed:
        print("[catalog-ids] 动作集快照有漂移（--check 未写入）", file=sys.stderr)
    rendered = render(read_service_ids())
    before = SNAPSHOT.read_text(encoding="utf-8") if SNAPSHOT.exists() else None
    if before == rendered:
        print(f"[catalog-ids] 快照是最新的（{len(json.loads(rendered)['service_ids'])} 个 service id）")
        return 1 if (check and actions_changed) else 0
    added = removed = 0
    if before:
        old = set(json.loads(before)["service_ids"])
        new = set(json.loads(rendered)["service_ids"])
        added, removed = len(new - old), len(old - new)
        print(f"[catalog-ids] 漂移：新增 {added} / 消失 {removed}")
        for name in sorted(new - old)[:20]:
            print(f"  + {name}")
        for name in sorted(old - new)[:20]:
            print(f"  - {name}")
    if check:
        print("[catalog-ids] --check：有漂移，未写入", file=sys.stderr)
        return 1
    SNAPSHOT.parent.mkdir(parents=True, exist_ok=True)
    SNAPSHOT.write_text(rendered, encoding="utf-8")
    print(f"[catalog-ids] 已写入 {SNAPSHOT}（{json.loads(rendered)['count']} 个 service id）")
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
